function getTraditionalToSimplifiedConverter() {
  if (!traditionalToSimplified) {
    traditionalToSimplified = require("opencc-js").Converter({ from: "tw", to: "cn" });
  }
  return traditionalToSimplified;
}

function countHan(value = "") {
  return (String(value || "").match(/\p{Script=Han}/gu) || []).length;
}

export function convertTraditionalToSimplified(value = "") {
  return getTraditionalToSimplifiedConverter()(String(value || ""));
}

export function looksLikeTraditionalChinese(value = "") {
  const text = normalizeText(value);
  if (!text || /[\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}]/u.test(text)) {
    return false;
  }
  const hanCount = countHan(text);
  if (hanCount < 2) return false;
  if (TRADITIONAL_HINT_PATTERN.test(text)) return true;

  const converted = convertTraditionalToSimplified(text);
  const convertedChars = Array.from(converted);
  const changedHanCount = Array.from(text).reduce((count, char, index) => {
    return /\p{Script=Han}/u.test(char) && char !== convertedChars[index] ? count + 1 : count;
  }, 0);
  return changedHanCount >= 2 && changedHanCount / Math.max(1, hanCount) >= 0.08;
}

export function canConvertTraditionalToSimplified(value = "", targetLanguage = "") {
  return /^zh-CN$/i.test(String(targetLanguage || "").trim()) && looksLikeTraditionalChinese(value);
}
